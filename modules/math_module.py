def collatz_sequence(n: int) -> List[int]:
    sequence = [n]
    while n != 1:
        if n % 2 == 0:
            n //= 2
        else:
            n = 3 * n + 1
        sequence.append(n)
        if len(sequence) > 200_000:
            raise ValueError("Sequence became too long.")
    return sequence


