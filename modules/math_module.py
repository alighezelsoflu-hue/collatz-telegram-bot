# ============================================================


def parse_paramplot_args(args: Sequence[str]) -> Tuple[str, str, float, float]:
    if not args:
        raise ValueError("Please provide x(t) and y(t).")
    text = " ".join(args)
    lowered = [arg.lower() for arg in args]
    tmin, tmax = 0.0, math.tau
    before = text
    if "range" in lowered:
        idx = lowered.index("range")
        before = " ".join(args[:idx])
        range_args = args[idx + 1:]
        if len(range_args) != 2:
            raise ValueError("Range must be: range tmin tmax")
        tmin = float(range_args[0])
        tmax = float(range_args[1])

    if ";" in before:
        x_expr, y_expr = [part.strip() for part in before.split(";", 1)]
    elif "," in before:
        x_expr, y_expr = [part.strip() for part in before.split(",", 1)]
    else:
        parts = before.split()
        if len(parts) < 2:
            raise ValueError("Use semicolon between expressions, e.g. cos(t); sin(t)")
        x_expr = parts[0]
        y_expr = " ".join(parts[1:])

    if not x_expr or not y_expr:
        raise ValueError("Both x(t) and y(t) are required.")
    if tmin >= tmax:
        raise ValueError("tmin must be smaller than tmax.")
    return x_expr, y_expr, tmin, tmax


async def paramplot_command(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    if not update.message:
        return
    try:
        x_expr, y_expr, tmin, tmax = parse_paramplot_args(context.args)
        points = []
        for t, _ in sample_even_x(tmin, tmax, MAX_PLOT_SAMPLES):
            try:
                x = evaluate_function(x_expr, "t", t)
                y = evaluate_function(y_expr, "t", t)
                if math.isfinite(x) and math.isfinite(y):
                    points.append((x, y))
                else:
                    points.append(None)
            except Exception:
                points.append(None)
        image = create_xy_plot_image(
            [{"points": points, "color": "#1f77b4", "width": 4}],
            title=f"Parametric plot: x={x_expr}, y={y_expr}",
            xlabel="x(t)",
            ylabel="y(t)",
            filename="parametric_plot.png",
        )
    except Exception as error:
        await update.message.reply_text(
            f"Parametric plot error.\n\nError: {error}\n\n"
            "Usage:\n/paramplot cos(t); sin(t) range 0 6.28\n/paramplot sin(3*t); sin(4*t) range 0 6.28"
        )
        return
    await send_plot(update, image, f"Parametric plot: x={x_expr}, y={y_expr}")


