def nice_number(value: float) -> str:
    if not math.isfinite(value):
        return str(value)
    value = clean_number(value)
    if abs(value - round(value)) < 1e-9:
        return str(int(round(value)))
    return f"{value:.4g}"


def robust_range(values: List[float], include_zero: bool = True) -> Tuple[float, float]:
    finite = sorted(v for v in values if math.isfinite(v) and abs(v) < 1e100)
    if not finite:
        return -1.0, 1.0
    low_index = max(0, int(len(finite) * 0.02))
    high_index = min(len(finite) - 1, int(len(finite) * 0.98))
    low = finite[low_index]
    high = finite[high_index]
    if include_zero:
        low = min(low, 0.0)
        high = max(high, 0.0)
    if abs(high - low) < 1e-12:
        low -= 1.0
        high += 1.0
    padding = (high - low) * 0.10
    return low - padding, high + padding


