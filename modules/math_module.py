def clean_number(value: float, eps: float = 1e-10) -> float:
    if abs(value) < eps:
        return 0.0
    return value


def format_real_number(value: float, digits: int = 10) -> str:
    value = clean_number(float(value))
    if math.isfinite(value) and abs(value - round(value)) < 1e-10:
        return str(int(round(value)))
    return f"{value:.{digits}g}"


def format_complex_number(value: complex) -> str:
    real = clean_number(value.real)
    imag = clean_number(value.imag)

    if imag == 0:
        return format_real_number(real)
    if real == 0:
        return f"{format_real_number(imag)}i"

    sign = "+" if imag > 0 else "-"
    return f"{format_real_number(real)} {sign} {format_real_number(abs(imag))}i"


