def split_top_level_values(text: str) -> List[str]:
    parts = []
    current = []
    depth = 0

    for char in text:
        if char == "(":
            depth += 1
            current.append(char)
        elif char == ")":
            depth = max(0, depth - 1)
            current.append(char)
        elif char in ",;" and depth == 0:
            item = "".join(current).strip()
            if item:
                parts.append(item)
            current = []
        else:
            current.append(char)

    item = "".join(current).strip()
    if item:
        parts.append(item)

    return parts


def parse_number_list(args: Sequence[str]) -> List[float]:
    if not args:
        raise ValueError("Please provide numbers.")
    text = " ".join(args)
    raw_parts = split_top_level_values(text)
    if len(raw_parts) == 1 and "," not in text and ";" not in text:
        raw_parts = [part.strip() for part in text.split() if part.strip()]
    values = [safe_eval_expression(part) for part in raw_parts]
    if not values:
        raise ValueError("No numbers found.")
    return values


def mode_text(values: List[float]) -> str:
    rounded = [round(v, 12) for v in values]
    counts = Counter(rounded)
    highest = max(counts.values())
    if highest <= 1:
        return "Mo = ∅"
    if len(set(counts.values())) == 1:
        return "Mo = ∅"
    modes = [value for value, count in counts.items() if count == highest]
    return "Mo = " + ", ".join(format_real_number(v) for v in modes)


def build_stats_report(values: List[float]) -> str:
    sorted_values = sorted(values)
    count = len(values)
    total = sum(values)
    mean = statistics.mean(values)
    median = statistics.median(values)
    min_value = min(values)
    max_value = max(values)
    value_range = max_value - min_value

    lines = [
        "Statistics report",
        "",
        f"Count: n = {count}",
        f"Sum: Σx = {format_real_number(total)}",
        f"Mean: x̄ = {format_real_number(mean)}",
        f"Median: {format_real_number(median)}",
        f"Mode: {mode_text(values)}",
        f"Minimum: {format_real_number(min_value)}",
        f"Maximum: {format_real_number(max_value)}",
        f"Range: {format_real_number(value_range)}",
    ]

    if count >= 2:
        lines.extend(
            [
                f"Sample variance: s² = {format_real_number(statistics.variance(values))}",
                f"Sample standard deviation: s = {format_real_number(statistics.stdev(values))}",
                f"Population variance: σ² = {format_real_number(statistics.pvariance(values))}",
                f"Population standard deviation: σ = {format_real_number(statistics.pstdev(values))}",
            ]
        )

    lines.extend(["", "Sorted values:", ", ".join(format_real_number(v) for v in sorted_values)])
    return "\n".join(lines)


