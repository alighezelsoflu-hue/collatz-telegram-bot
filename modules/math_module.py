def create_fib_spiral_image(n: int) -> BytesIO:
    if n < 2:
        raise ValueError("Use at least 2 squares.")
    if n > 16:
        raise ValueError("Maximum Fibonacci spiral size is 16.")
    fibs = [1, 1]
    for _ in range(2, n):
        fibs.append(fibs[-1] + fibs[-2])

    # Place squares in a spiral using directions right, up, left, down.
    squares = []
    x, y = 0, 0
    squares.append((x, y, fibs[0], 0))
    x += fibs[0]
    squares.append((x, y, fibs[1], 1))
    directions = [(0, -1), (-1, 0), (0, 1), (1, 0)]
    for i in range(2, n):
        size = fibs[i]
        direction_index = (i - 2) % 4
        dx, dy = directions[direction_index]
        if direction_index == 0:  # up
            x = squares[-1][0]
            y = squares[-1][1] - size
        elif direction_index == 1:  # left
            x = squares[-1][0] - size
            y = squares[-1][1]
        elif direction_index == 2:  # down
            x = squares[-1][0]
            y = squares[-1][1] + squares[-1][2]
        else:  # right
            x = squares[-1][0] + squares[-1][2]
            y = squares[-1][1]
        squares.append((x, y, size, direction_index))

    min_x = min(s[0] for s in squares)
    min_y = min(s[1] for s in squares)
    max_x = max(s[0] + s[2] for s in squares)
    max_y = max(s[1] + s[2] for s in squares)
    width = 1100
    height = 850
    margin = 70
    scale = min((width - 2 * margin) / (max_x - min_x), (height - 2 * margin) / (max_y - min_y))

    image = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(image)
    title_font = load_plot_font(32)
    small_font = load_plot_font(16)
    draw.text((margin, 25), f"Fibonacci spiral with {n} squares", fill="black", font=title_font)

    def tx(v: float) -> int:
        return int(margin + (v - min_x) * scale)

    def ty(v: float) -> int:
        return int(margin + 45 + (v - min_y) * scale)

    for i, (sx, sy, size, direction_index) in enumerate(squares):
        x1, y1, x2, y2 = tx(sx), ty(sy), tx(sx + size), ty(sy + size)
        draw.rectangle((x1, y1, x2, y2), outline="#333333", width=2)
        draw.text((x1 + 5, y1 + 5), str(size), fill="#555555", font=small_font)

        # Approximate spiral quarter arcs.
        if i == 0:
            continue
        if direction_index == 0:
            bbox = (x1, y1, x2 * 2 - x1, y2 * 2 - y1)
            start, end = 180, 270
        elif direction_index == 1:
            bbox = (x1, y1, x2, y2)
            start, end = 270, 360
        elif direction_index == 2:
            bbox = (x1, y1, x2, y2)
            start, end = 0, 90
        else:
            bbox = (x1, y1, x2, y2)
            start, end = 90, 180
        try:
            draw.arc(bbox, start=start, end=end, fill="#d62728", width=4)
        except Exception:
            pass

    output = BytesIO()
    image.save(output, format="PNG")
    output.seek(0)
    output.name = "fibonacci_spiral.png"
    return output


async def fibspiral_command(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    if not update.message:
        return
    try:
        n = parse_positive_int(context.args, "Fibonacci spiral size", max_value=16)
        image = create_fib_spiral_image(n)
    except Exception as error:
        await update.message.reply_text(f"Fibonacci spiral error.\n\nError: {error}\n\nUsage:\n/fibspiral 10")
        return
    await send_plot(update, image, f"Fibonacci spiral with {n} squares")


