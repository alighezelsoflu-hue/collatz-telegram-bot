def parse_at_command(args: Sequence[str], keyword: str = "at") -> Tuple[str, float]:
    lowered = [arg.lower() for arg in args]
    if keyword not in lowered:
        raise ValueError(f"Use: {keyword} x0")
    idx = lowered.index(keyword)
    expr = " ".join(args[:idx]).strip()
    rest = args[idx + 1:]
    if len(rest) != 1:
        raise ValueError(f"Use exactly one number after {keyword}.")
    if not expr:
        raise ValueError("Expression is empty.")
    return expr, float(rest[0])


def numerical_derivative(expr: str, x: float) -> float:
    h = 1e-5 * max(1.0, abs(x))
    return (evaluate_function(expr, "x", x + h) - evaluate_function(expr, "x", x - h)) / (2 * h)


def tangent_line_value(slope: float, x0: float, y0: float, x: float) -> float:
    return slope * (x - x0) + y0


