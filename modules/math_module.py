def parse_from_to(args: Sequence[str]) -> Tuple[str, float, float]:
    lowered = [arg.lower() for arg in args]
    if "from" not in lowered or "to" not in lowered:
        raise ValueError("Use: from a to b")
    from_idx = lowered.index("from")
    to_idx = lowered.index("to")
    if to_idx <= from_idx:
        raise ValueError("Use: from a to b")
    expr = " ".join(args[:from_idx]).strip()
    if not expr:
        raise ValueError("Expression is empty.")
    if to_idx != from_idx + 2:
        raise ValueError("Use exactly one number after from.")
    if len(args) != to_idx + 2:
        raise ValueError("Use exactly one number after to.")
    a = float(args[from_idx + 1])
    b = float(args[to_idx + 1])
    if a == b:
        raise ValueError("Integration bounds cannot be equal.")
    return expr, a, b


def numerical_integral(expr: str, a: float, b: float, n: int = 1000) -> float:
    if n % 2 == 1:
        n += 1
    h = (b - a) / n
    total = evaluate_function(expr, "x", a) + evaluate_function(expr, "x", b)
    for i in range(1, n):
        x = a + i * h
        total += (4 if i % 2 else 2) * evaluate_function(expr, "x", x)
    return total * h / 3


