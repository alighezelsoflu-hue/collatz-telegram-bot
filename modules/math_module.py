def parse_start_command(args: Sequence[str]) -> Tuple[str, float]:
    lowered = [arg.lower() for arg in args]
    if "start" not in lowered:
        raise ValueError("Use: start x0")
    idx = lowered.index("start")
    expr = " ".join(args[:idx]).strip()
    rest = args[idx + 1:]
    if not expr:
        raise ValueError("Expression is empty.")
    if len(rest) != 1:
        raise ValueError("Use exactly one start value.")
    return expr, float(rest[0])


def newton_iterations(expr: str, start: float, max_iter: int = 20) -> List[Tuple[int, float, float]]:
    x = start
    result = []
    for i in range(max_iter):
        y = evaluate_function(expr, "x", x)
        result.append((i, x, y))
        if abs(y) < 1e-10:
            break
        d = numerical_derivative(expr, x)
        if abs(d) < 1e-12:
            raise ValueError("Derivative became too close to zero.")
        x = x - y / d
        if not math.isfinite(x) or abs(x) > 1e12:
            raise ValueError("Newton method diverged.")
    return result


async def newton_command(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    if not update.message:
        return
    try:
        expr, start = parse_start_command(context.args)
        iterations = newton_iterations(expr, start)
        root = iterations[-1][1]
        xmin = min(x for _, x, _ in iterations) - 2
        xmax = max(x for _, x, _ in iterations) + 2
        if xmin == xmax:
            xmin, xmax = root - 5, root + 5
        points = sample_function_points(expr, xmin, xmax, "x")
        marks = [(x, y, f"x{i}") for i, x, y in iterations[:8]]
        image = create_xy_plot_image(
            [{"points": points, "color": "#1f77b4", "width": 4}],
            title=f"Newton method: f(x) = {expr}",
            x_range=(xmin, xmax),
            xlabel="x",
            ylabel="f(x)",
            points_to_mark=marks,
            filename="newton_plot.png",
        )
        lines = ["Newton method", "", f"f(x) = {expr}", f"Approx root: x ≈ {format_real_number(root, digits=14)}", "", "Iterations:"]
        for i, x, y in iterations:
            lines.append(f"x{i} = {format_real_number(x, digits=12)}, f(x{i}) = {format_real_number(y, digits=12)}")
    except Exception as error:
        await update.message.reply_text(f"Newton method error.\n\nError: {error}\n\nUsage:\n/newton x^3 - x - 2 start 1")
        return
    await update.message.reply_text("\n".join(lines))
    await send_plot(update, image, f"Newton root ≈ {format_real_number(root, digits=14)}")


