def primes_less_than(limit: int) -> List[int]:
    if limit <= 2:
        return []
    sieve = bytearray(b"\x01") * limit
    sieve[0:2] = b"\x00\x00"
    max_check = int(limit ** 0.5) + 1
    for number in range(2, max_check):
        if sieve[number]:
            start = number * number
            count = ((limit - 1 - start) // number) + 1
            sieve[start:limit:number] = b"\x00" * count
    return [number for number in range(limit) if sieve[number]]


