async def polarplot_command(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    if not update.message:
        return
    try:
        expr, theta_min, theta_max = parse_keyword_range(context.args, default=(0.0, math.tau))
        points = []
        for theta, _ in sample_even_x(theta_min, theta_max, MAX_PLOT_SAMPLES):
            try:
                r = evaluate_function(expr, "theta", theta)
                x = r * math.cos(theta)
                y = r * math.sin(theta)
                if math.isfinite(x) and math.isfinite(y):
                    points.append((x, y))
                else:
                    points.append(None)
            except Exception:
                points.append(None)
        image = create_xy_plot_image(
            [{"points": points, "color": "#1f77b4", "width": 4}],
            title=f"Polar plot: r = {expr}",
            xlabel="x",
            ylabel="y",
            filename="polar_plot.png",
        )
    except Exception as error:
        await update.message.reply_text(
            f"Polar plot error.\n\nError: {error}\n\nUsage:\n/polarplot 1 + sin(theta) range 0 6.28"
        )
        return
    await send_plot(update, image, f"Polar plot of r = {expr}")


