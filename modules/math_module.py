class SafeEvalError(ValueError):
    pass


def normalize_expression(expr: str) -> str:
    return (
        expr.strip()
        .replace("^", "**")
        .replace("÷", "/")
        .replace("×", "*")
        .replace("−", "-")
        .replace("θ", "theta")
    )


def safe_eval_expression(expr: str, variables: Optional[Dict[str, float]] = None) -> float:
    expr = normalize_expression(expr)
    if not expr:
        raise SafeEvalError("Expression is empty.")
    if len(expr) > 500:
        raise SafeEvalError("Expression is too long.")

    names = dict(ALLOWED_CONSTANTS)
    if variables:
        names.update(variables)

    tree = ast.parse(expr, mode="eval")

    def eval_node(node: ast.AST) -> Any:
        if isinstance(node, ast.Expression):
            return eval_node(node.body)

        if isinstance(node, ast.Constant):
            if isinstance(node.value, (int, float)):
                return node.value
            raise SafeEvalError("Only numeric constants are allowed.")

        if isinstance(node, ast.Name):
            if node.id in names:
                return names[node.id]
            raise SafeEvalError(f"Unknown name: {node.id}")

        if isinstance(node, ast.BinOp):
            op_type = type(node.op)
            if op_type not in BIN_OPS:
                raise SafeEvalError("Operator is not allowed.")
            left = eval_node(node.left)
            right = eval_node(node.right)
            return BIN_OPS[op_type](left, right)

        if isinstance(node, ast.UnaryOp):
            op_type = type(node.op)
            if op_type not in UNARY_OPS:
                raise SafeEvalError("Unary operator is not allowed.")
            return UNARY_OPS[op_type](eval_node(node.operand))

        if isinstance(node, ast.Call):
            if not isinstance(node.func, ast.Name):
                raise SafeEvalError("Only simple function calls are allowed.")
            func_name = node.func.id
            if func_name not in ALLOWED_FUNCTIONS:
                raise SafeEvalError(f"Function not allowed: {func_name}")
            if len(node.args) > 10:
                raise SafeEvalError("Too many function arguments.")
            args = [eval_node(arg) for arg in node.args]
            return ALLOWED_FUNCTIONS[func_name](*args)

        raise SafeEvalError("Expression contains unsupported syntax.")

    result = eval_node(tree)
    if not isinstance(result, (int, float)):
        raise SafeEvalError("Expression did not return a number.")
    return float(result)


def evaluate_function(expr: str, variable_name: str, variable_value: float) -> float:
    variables = {
        variable_name: variable_value,
        "x": variable_value if variable_name == "x" else 0.0,
        "t": variable_value if variable_name == "t" else 0.0,
        "theta": variable_value if variable_name == "theta" else 0.0,
    }
    return safe_eval_expression(expr, variables)


